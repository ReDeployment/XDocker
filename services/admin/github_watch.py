SHA=re.compile(r'^[a-f0-9]{40}$')
BAD={'failure','failed','error','cancelled','timed_out','action_required','startup_failure','stale'}
LIMIT=2*1024*1024


def stamp():return datetime.now(timezone.utc).isoformat()
def digest(value):return hashlib.sha256(json.dumps(value,sort_keys=True,separators=(',',':')).encode()).hexdigest()
def sha(value):return value if isinstance(value,str) and SHA.fullmatch(value) else None
def integer(value):return type(value) is int and 0<value<2**63


def safe_text(value,token='',limit=2000):
    text=value if isinstance(value,str) else ''
    if token:text=text.replace(token,'[REDACTED]')
    text=re.sub(r'-----BEGIN [^-]*PRIVATE KEY-----.*?-----END [^-]*PRIVATE KEY-----','[PRIVATE KEY REDACTED]',text,flags=re.S)
    text=re.sub(r'(?i)((?:bearer|basic)\s+)[\w.+/=-]+',r'\1[REDACTED]',text)
    text=re.sub(r'\b(?:gh[pousr]_|github_pat_)[A-Za-z0-9_]+','[REDACTED]',text)
    text=re.sub(r'''(?i)((?:token|password|secret|authorization|api[_-]?key)["']?\s*[=:]\s*)(?:"[^"]*"|'[^']*'|[^\s,;}]+)''',r'\1[REDACTED]',text)
    text=re.sub(r'://[^\s/@]+:[^\s/@]+@','://[REDACTED]@',text)
    return ''.join(c for c in text if c in '\n\t' or ord(c)>=32)[:limit]


class WatchError(ValueError):
    def __init__(self,code,retry_at=0):super().__init__(code);self.retry_at=retry_at


def owner_token(root,repo):
    owner=repo.split('/')[0].lower();file=Path(root)/'credentials'/(owner+'.token');token=''
    if file.exists() or file.is_symlink():
        if file.is_symlink() or file.parent.is_symlink() or file.stat().st_mode&0o077 or file.stat().st_size>1024:raise WatchError('github-credential-unsafe')
        token=file.read_text().strip()
        if not re.fullmatch(r'[A-Za-z0-9_\-.]{20,1024}',token):raise WatchError('github-credential-invalid')
    return token


class NoRedirect(urllib.request.HTTPRedirectHandler):
    def redirect_request(self,*args,**kw):return None


class GitHubReader:
    def __init__(self,repo,token='',gh=False):
        if repo not in PROJECTS.values():raise WatchError('repository-not-allowlisted')
        self.repo=repo;self.token=token;self.gh=gh
        self.opener=urllib.request.build_opener(NoRedirect)
        self.deadline=time.monotonic()+45

    def get(self,path=''):
        # Paths are generated by the collector, never accepted by the HTTP API or from GitHub URLs.
        if time.monotonic()>=self.deadline:raise WatchError('collection-time-budget')
        endpoint='repos/'+self.repo+path
        if self.gh:
            try:
                call=subprocess.run(['gh','api','--method','GET',endpoint],capture_output=True,timeout=min(10,max(.1,self.deadline-time.monotonic())))
            except (OSError,subprocess.TimeoutExpired):raise WatchError('github-cli-unavailable') from None
            if call.returncode or len(call.stdout)>LIMIT:raise WatchError('github-cli-unconfirmed')
            raw=call.stdout;more=False
        else:
            headers={'Accept':'application/vnd.github+json','User-Agent':'XDocker-GitHub-Watch','X-GitHub-Api-Version':'2022-11-28'}
            if self.token:headers['Authorization']='Bearer '+self.token
            try:
                with self.opener.open(urllib.request.Request('https://api.github.com/'+endpoint,headers=headers),timeout=min(8,max(.1,self.deadline-time.monotonic()))) as response:
                    raw=response.read(LIMIT+1);more='rel="next"' in response.headers.get('Link','')
            except urllib.error.HTTPError as error:
                code=error.code;retry=0
                try:
                    if code==429 or (code==403 and error.headers.get('X-RateLimit-Remaining')=='0'):
                        retry=min(time.time()+86400,max(time.time()+60,float(error.headers.get('X-RateLimit-Reset','0'))))
                        raise WatchError('rate-limited',retry)
                    if error.headers.get('Retry-After'):
                        retry=time.time()+min(86400,max(60,int(error.headers['Retry-After'])))
                    raise WatchError('github-http-'+str(code),retry)
                except (TypeError,ValueError) as failure:
                    if isinstance(failure,WatchError):raise
                    raise WatchError('github-http-'+str(code),time.time()+60) from None
                finally:error.close()
            except (OSError,ValueError):raise WatchError('github-network-unconfirmed') from None
        if len(raw)>LIMIT:raise WatchError('github-response-too-large')
        try:data=json.loads(raw)
        except (ValueError,UnicodeError):raise WatchError('github-response-invalid') from None
        if not isinstance(data,(dict,list)):raise WatchError('github-response-invalid')
        return data,more


def sequence(reader,path,key=None):
    data,more=reader.get(path)
    rows=data.get(key) if key and isinstance(data,dict) else data
    if not isinstance(rows,list) or any(not isinstance(r,dict) for r in rows):raise WatchError('github-response-invalid')
    total=data.get('total_count') if key and isinstance(data,dict) else None
    complete=not more and len(rows)<100
    if total is not None:complete=not more and type(total) is int and total==len(rows) and total<=100
    return rows,complete


def condition(checks,complete,required):
    if required:
        names={c['name'] for c in checks}
        if not set(required)<=names:return 'unknown'
        checks=[c for c in checks if c['name'] in required]
    if any(c['conclusion'] in BAD for c in checks):return 'blocked'
    if any(c['status']!='completed' for c in checks):return 'waiting'
    names={c['name'] for c in checks}
    if not complete or not checks or not set(required)<=names:return 'unknown'
    if any(c['conclusion']!='success' for c in checks):return 'unknown'
    return 'observed-pass'


def collect_project(settings,reader):
    repo=settings['repository'];base='https://github.com/'+repo;observations={}
    metadata,_=reader.get()
    if not isinstance(metadata,dict) or str(metadata.get('full_name','')).lower()!=repo.lower():raise WatchError('repository-identity-unconfirmed')
    default=metadata.get('default_branch')
    if not isinstance(default,str) or not default:raise WatchError('default-branch-unconfirmed')
    branches=settings['branches'] or [default]
    heads=[]
    for branch in branches:
        data,_=reader.get('/branches/'+quote(branch,safe=''))
        revision=sha(data.get('commit',{}).get('sha')) if isinstance(data,dict) else None
        if not revision:raise WatchError('branch-head-unconfirmed')
        row={'branch':branch,'sha':revision,'url':base+'/commit/'+revision};heads.append(row)
        observations['branch:'+branch]={'kind':'push-observation','sha':revision,'title':'分支头提交已变化：'+branch,'url':row['url'],'branch':branch}
    pulls,_=sequence(reader,'/pulls?state=all&sort=updated&direction=desc&per_page=10')
    prs=[];tracked={h['sha'] for h in heads};open_count=0;review_complete=True
    for raw in pulls[:10]:
        number=raw.get('number');head=sha(raw.get('head',{}).get('sha'))
        if not integer(number) or not head:raise WatchError('pull-identity-unconfirmed')
        row={'number':number,'title':safe_text(raw.get('title'),reader.token,300),'sha':head,'state':raw.get('state') if raw.get('state') in ('open','closed') else 'unknown',
             'draft':raw.get('draft') is True,'url':base+'/pull/'+str(number),'review':'not-collected','historical_reviews':0}
        observations['pr:'+str(number)]={'kind':'pull-request','sha':head,'title':'PR #'+str(number)+' '+row['title'],'url':row['url'],'state':row['state'],'draft':row['draft']}
        if row['state']=='open' and open_count<3:
            open_count+=1;tracked.add(head)
            reviews,complete=sequence(reader,'/pulls/'+str(number)+'/reviews?per_page=100');review_complete &= complete
            latest={}
            for review in sorted(reviews,key=lambda r:r.get('id',0)):
                if review.get('state') not in ('APPROVED','CHANGES_REQUESTED','COMMENTED','DISMISSED'):continue
                rid=review.get('id');actor=safe_text(review.get('user',{}).get('login'),reader.token,100)
                if not integer(rid):raise WatchError('review-identity-unconfirmed')
                commit=sha(review.get('commit_id'));state=review['state'];url=row['url']+'#pullrequestreview-'+str(rid)
                observations['review:'+str(rid)]={'kind':'review','sha':commit,'title':state+' · PR #'+str(number),'body':safe_text(review.get('body'),reader.token),
                    'actor':actor,'url':url,'state':state,'pr':number,'binding':'current-head' if commit==head else 'historical-or-unbound'}
                if state!='COMMENTED' and actor:latest[actor]=(state,commit)
            current=[s for s,h in latest.values() if h==head];old_changes=any(s=='CHANGES_REQUESTED' and h!=head for s,h in latest.values())
            row['historical_reviews']=sum(h!=head for _,h in latest.values())
            row['review']='changes-requested' if 'CHANGES_REQUESTED' in current else 'needs-recheck' if old_changes else 'unknown' if not complete else 'approved-observed' if 'APPROVED' in current else 'no-current-approval'
        prs.append(row)
    ci=[];failed_jobs=[]
    for revision in sorted(tracked):
        checks,checks_complete=sequence(reader,'/commits/'+revision+'/check-runs?filter=latest&per_page=100','check_runs')
        runs,runs_complete=sequence(reader,'/actions/runs?'+urlencode({'head_sha':revision,'per_page':100}),'workflow_runs')
        status,more=reader.get('/commits/'+revision+'/status?per_page=100')
        if not isinstance(status,dict) or not isinstance(status.get('statuses'),list):raise WatchError('github-response-invalid')
        status_complete=not more and type(status.get('total_count')) is int and status['total_count']==len(status['statuses']) and status['total_count']<100
        entries=[]
        for check in checks:
            if sha(check.get('head_sha'))!=revision or not integer(check.get('id')):raise WatchError('check-identity-unconfirmed')
            row={'name':safe_text(check.get('name'),reader.token,200),'status':check.get('status') if check.get('status') in ('queued','in_progress','completed') else 'unknown',
                 'conclusion':check.get('conclusion') if check.get('conclusion') in BAD|{'success','neutral','skipped',None} else 'unknown','url':base+'/commit/'+revision+'/checks'}
            entries.append(row)
            observations['check:'+str(check['id'])]={'kind':'check','sha':revision,'title':row['name'],'status':row['status'],'conclusion':row['conclusion'],'url':row['url']}
            output=check.get('output') if isinstance(check.get('output'),dict) else {}
            if row['conclusion'] in BAD:
                row['summary']=safe_text(output.get('summary'),reader.token)
                observations['check:'+str(check['id'])]['body']=row['summary']
                if integer(output.get('annotations_count')):
                    annotations,complete=sequence(reader,'/check-runs/'+str(check['id'])+'/annotations?per_page=100')
                    row['annotations']=[{'path':safe_text(a.get('path'),reader.token,300),'line':a.get('start_line') if integer(a.get('start_line')) else None,
                        'level':a.get('annotation_level') if a.get('annotation_level') in ('notice','warning','failure') else 'unknown',
                        'message':safe_text(a.get('message'),reader.token,1000)} for a in annotations[:30]]
                    checks_complete &= complete
        latest={}
        for run in runs:
            if sha(run.get('head_sha'))!=revision or not integer(run.get('id')) or not integer(run.get('workflow_id')):raise WatchError('run-identity-unconfirmed')
            identity=run['workflow_id'];order=(run['id'],run.get('run_attempt',1))
            if identity not in latest or order>latest[identity][0]:latest[identity]=(order,run)
        for _,run in latest.values():
            rid=run['id'];attempt=run.get('run_attempt',1)
            if not integer(attempt):raise WatchError('run-identity-unconfirmed')
            row={'name':safe_text(run.get('name'),reader.token,200),'status':run.get('status') if run.get('status') in ('queued','in_progress','completed','waiting','requested','pending') else 'unknown',
                 'conclusion':run.get('conclusion') if run.get('conclusion') in BAD|{'success','neutral','skipped',None} else 'unknown','url':base+'/actions/runs/'+str(rid),'run_id':rid,'attempt':attempt}
            entries.append(row);observations['run:'+str(rid)]={'kind':'workflow','sha':revision,**row,'title':row['name']}
            if row['conclusion'] in BAD and len(failed_jobs)<3:
                jobs,complete=sequence(reader,'/actions/runs/'+str(rid)+'/attempts/'+str(attempt)+'/jobs?per_page=100','jobs')
                for job in jobs:
                    if job.get('conclusion') in BAD:
                        failed_jobs.append({'run_id':rid,'attempt':attempt,'sha':revision,'name':safe_text(job.get('name'),reader.token,200),
                            'steps':[safe_text(s.get('name'),reader.token,200) for s in job.get('steps',[]) if s.get('conclusion') in BAD], 'url':row['url']})
                runs_complete &= complete
        for raw in status['statuses']:
            if not isinstance(raw,dict):raise WatchError('github-response-invalid')
            state=raw.get('state');entries.append({'name':safe_text(raw.get('context'),reader.token,200),
                'status':'completed' if state in ('success','failure','error') else 'pending','conclusion':state,'url':base+'/commit/'+revision+'/checks'})
        ci.append({'sha':revision,'state':condition(entries,checks_complete and runs_complete and status_complete,settings['required_checks']),
                   'checks':entries,'complete':checks_complete and runs_complete and status_complete})
    comments=[];numbers={p['number']:p for p in prs}
    for kind,path in (('comment','/issues/comments?sort=updated&direction=desc&per_page=30'),('review-comment','/pulls/comments?sort=updated&direction=desc&per_page=30')):
        rows,_=sequence(reader,path)
        for raw in rows[:30]:
            identifier=raw.get('id');url=raw.get('issue_url') if kind=='comment' else raw.get('pull_request_url')
            prefix='https://api.github.com/repos/'+repo+('/issues/' if kind=='comment' else '/pulls/')
            match=re.fullmatch(re.escape(prefix)+r'([0-9]+)',url or '',re.I)
            if not integer(identifier) or not match:continue
            number=int(match[1]);commit=sha(raw.get('commit_id'));pr=numbers.get(number)
            if kind=='comment' and pr is None:continue  # Issue-only comments are outside this PR observer.
            row={'kind':kind,'id':identifier,'pr':number,'sha':commit,'body':safe_text(raw.get('body'),reader.token),
                'actor':safe_text(raw.get('user',{}).get('login'),reader.token,100),'path':safe_text(raw.get('path'),reader.token,300),
                'line':raw.get('line') if integer(raw.get('line')) else None,
                'binding':'current-head' if commit and pr and commit==pr['sha'] else 'historical' if commit else 'unbound',
                'url':base+'/pull/'+str(number)+('#issuecomment-' if kind=='comment' else '#discussion_r')+str(identifier),
                'updated_at':safe_text(raw.get('updated_at'),reader.token,100)}
            comments.append(row);observations[kind+':'+str(identifier)]={**row,'title':'PR #'+str(number)+' 评论待人工核对'}
    state='blocked' if any(r['state']=='blocked' for r in ci) or any(p['review']=='changes-requested' for p in prs) else 'waiting' if any(r['state']=='waiting' for r in ci) else 'attention' if any(p['state']=='open' and p['review']!='approved-observed' for p in prs) else 'unknown' if any(r['state']=='unknown' for r in ci) else 'observed-pass'
    return {'repository':repo,'checked_at':stamp(),'private':metadata.get('private') is True,'state':state,'heads':heads,'pulls':prs,'ci':ci,
            'failed_jobs':failed_jobs[:30],'comments':comments,'review_complete':review_complete,'observations':observations,
            'publish_authorized':False,'scope':'最近10个PR/30条每类评论、最多3个开放PR及配置分支的提交；不是完整Webhook事件流或发布授权'}


class WatchStore:
    def __init__(self,state):
        self.root=Path(state)/'github';self.file=self.root/'watch.sqlite3'
        if self.root.is_symlink() or self.root.parent.is_symlink() or self.file.is_symlink():raise WatchError('watch-storage-unsafe')
        self.root.mkdir(mode=0o700,parents=True,exist_ok=True);self.root.chmod(0o700)
        with self.db() as db:
            version=db.execute('PRAGMA user_version').fetchone()[0]
            if version not in (0,1):raise WatchError('watch-schema-unknown')
            db.executescript('''CREATE TABLE IF NOT EXISTS projects (id TEXT PRIMARY KEY, enabled INTEGER NOT NULL, branches TEXT NOT NULL, required_checks TEXT NOT NULL,
                revision TEXT NOT NULL, status TEXT, attempted TEXT, success TEXT, retry_at REAL NOT NULL DEFAULT 0, snapshot TEXT);
                CREATE TABLE IF NOT EXISTS notifications (id INTEGER PRIMARY KEY AUTOINCREMENT, project TEXT NOT NULL, kind TEXT NOT NULL, at TEXT NOT NULL,
                payload TEXT NOT NULL, read_at TEXT); PRAGMA user_version=1;''')
            for project in PROJECTS:
                db.execute('INSERT OR IGNORE INTO projects(id,enabled,branches,required_checks,revision,status) VALUES(?,1,?,?,?,?)',
                           (project,'[]','[]',os.urandom(16).hex(),'not-collected'))
        self.file.chmod(0o600)

    @contextmanager
    def db(self):
        if self.file.is_symlink():raise WatchError('watch-storage-unsafe')
        connection=sqlite3.connect(self.file,timeout=5);connection.row_factory=sqlite3.Row
        try:
            with connection:yield connection
        finally:connection.close()

    def settings(self,project):
        if project not in PROJECTS:raise WatchError('unknown-project')
        with self.db() as db:row=db.execute('SELECT * FROM projects WHERE id=?',(project,)).fetchone()
        if row is None:raise WatchError('watch-record-missing')
        branches=json.loads(row['branches']);required=json.loads(row['required_checks']);snapshot=json.loads(row['snapshot']) if row['snapshot'] else None
        if not isinstance(branches,list) or not isinstance(required,list) or (snapshot is not None and not isinstance(snapshot,dict)):
            raise WatchError('watch-record-invalid')
        return {'project':project,'repository':PROJECTS[project],'enabled':bool(row['enabled']),'branches':branches,
                'required_checks':required,'revision':row['revision'],'status':row['status'],
                'attempted_at':row['attempted'],'success_at':row['success'],'retry_at':row['retry_at'],
                'snapshot':snapshot}

    def configure(self,project,revision,enabled,branches,required):
        if project not in PROJECTS or type(enabled) is not bool or not isinstance(branches,list) or len(branches)>3 or not isinstance(required,list) or len(required)>30:
            raise WatchError('invalid-watch-settings')
        if any(not isinstance(v,str) or not 1<=len(v)<=150 or v.startswith('-') or '..' in v or any(ord(c)<32 for c in v) for v in branches+required):raise WatchError('invalid-watch-settings')
        with self.db() as db:
            count=db.execute("UPDATE projects SET enabled=?,branches=?,required_checks=?,revision=?,status='settings-changed' WHERE id=? AND revision=?",
                (int(enabled),json.dumps(list(dict.fromkeys(branches))),json.dumps(list(dict.fromkeys(required))),os.urandom(16).hex(),project,revision)).rowcount
            if count!=1:raise WatchError('watch-settings-changed')

    def begin(self,project):
        with self.db() as db:db.execute("UPDATE projects SET status='collecting',attempted=? WHERE id=?",(stamp(),project))

    def finish(self,settings,snapshot=None,error=None,retry_at=0):
        project=settings['project']
        with self.db() as db:
            current=db.execute('SELECT * FROM projects WHERE id=?',(project,)).fetchone()
            if current['revision']!=settings['revision']:
                db.execute("UPDATE projects SET status='settings-changed' WHERE id=?",(project,));return
            if error:
                total=db.execute('SELECT count(*) FROM notifications').fetchone()[0]
                if settings['status']!=error and total<10000:
                    db.execute('INSERT INTO notifications(project,kind,at,payload) VALUES(?,?,?,?)',
                        (project,'collection-error',stamp(),json.dumps({'kind':'collection-error','title':'采集未确认：'+error,'url':'https://github.com/'+PROJECTS[project]})))
                db.execute('UPDATE projects SET status=?,retry_at=? WHERE id=?',(error,retry_at,project));return
            previous=json.loads(current['snapshot']) if current['snapshot'] else None
            old=previous.get('observations',{}) if previous else {}
            if previous is None:
                changes=[{'kind':'baseline','title':'首次采集：'+snapshot['state'],'state':snapshot['state'],'url':'https://github.com/'+PROJECTS[project]}]
            else:changes=[row for key,row in snapshot['observations'].items() if key not in old or digest(row)!=digest(old[key])]
            db.execute('DELETE FROM notifications WHERE read_at IS NOT NULL AND id NOT IN (SELECT id FROM notifications ORDER BY id DESC LIMIT 2000)')
            if db.execute('SELECT count(*) FROM notifications').fetchone()[0]+min(100,len(changes))>10000:raise WatchError('inbox-full')
            for row in changes[:100]:
                db.execute('INSERT INTO notifications(project,kind,at,payload) VALUES(?,?,?,?)',(project,row['kind'],stamp(),json.dumps(row)))
            db.execute('UPDATE projects SET status=?,success=?,retry_at=0,snapshot=? WHERE id=?',('collected',stamp(),json.dumps(snapshot),project))

    def listing(self,before=None):
        if before is not None and (not integer(before)):raise WatchError('invalid-inbox-cursor')
        with self.db() as db:
            notifications=db.execute('SELECT * FROM notifications WHERE id<? ORDER BY id DESC LIMIT 50',(before or 2**63-1,)).fetchall()
            unread=db.execute('SELECT count(*) FROM notifications WHERE read_at IS NULL').fetchone()[0]
        projects=[self.settings(p) for p in PROJECTS]
        for row in projects:
            if row['snapshot']:row['snapshot'].pop('observations',None)
        return {'projects':projects,'notifications':[{'id':r['id'],'project':r['project'],'at':r['at'],
            'read':r['read_at'] is not None,'payload':json.loads(r['payload'])} for r in notifications],'unread':unread,
            'next_before':notifications[-1]['id'] if len(notifications)==50 else None,'publish_authorized':False}

    def summary(self):
        with self.db() as db:
            unread=db.execute('SELECT count(*) FROM notifications WHERE read_at IS NULL').fetchone()[0]
        return {'unread':unread,'projects':list(PROJECTS),'publish_authorized':False}

    def mark_read(self,identifiers):
        if not isinstance(identifiers,list) or not 1<=len(identifiers)<=50 or any(not integer(i) for i in identifiers):raise WatchError('invalid-inbox-selection')
        with self.db() as db:
            for identifier in identifiers:db.execute('UPDATE notifications SET read_at=? WHERE id=?',(stamp(),identifier))


class GitHubWatch:
    def __init__(self,state,enabled=False,interval=300,reader_factory=None):
        self.enabled=enabled;self.interval=interval;self.store=None;self.error=None;self.running=False;self.worker=None;self.leader=None
        self.stop_event=threading.Event();self.mutex=threading.Lock();self.reader_factory=reader_factory
        try:
            self.store=WatchStore(state)
            try:lease=self.lease('collect')
            except WatchError as error:
                if str(error)!='watch-busy':raise
            else:
                try:
                    with self.store.db() as db:db.execute("UPDATE projects SET status='interrupted' WHERE status='collecting'")
                finally:lease.close()
        except (OSError,ValueError,sqlite3.DatabaseError):self.error='watch-store-unavailable'

    def reader(self,settings):
        if self.reader_factory:return self.reader_factory(settings)
        return GitHubReader(settings['repository'],owner_token(self.store.root,settings['repository']))

    def collect(self,settings):
        if self.reader_factory:return collect_project(settings,self.reader(settings))
        inputs={k:settings[k] for k in ('project','repository','branches','required_checks')}
        try:
            call=subprocess.run([sys.executable,str(Path(__file__).resolve()),'--collect',str(self.store.root)],
                input=json.dumps(inputs).encode(),capture_output=True,timeout=50,check=False)
            if call.returncode not in (0,2) or len(call.stdout)>LIMIT:raise WatchError('collector-output-unconfirmed')
            data=json.loads(call.stdout)
            if call.returncode==2:
                code=data.get('error','collection-unconfirmed')
                if not isinstance(code,str) or not re.fullmatch(r'[a-z0-9-]{1,80}',code):raise WatchError('collector-output-unconfirmed')
                retry=data.get('retry_at',0)
                if type(retry) not in (int,float) or not 0<=retry<=time.time()+86401:retry=time.time()+60
                raise WatchError(code,retry)
            if not isinstance(data,dict) or data.get('repository')!=settings['repository'] or data.get('publish_authorized') is not False:
                raise WatchError('collector-output-unconfirmed')
            return data
        except subprocess.TimeoutExpired:raise WatchError('collection-hard-timeout') from None
        except (OSError,ValueError) as error:
            if isinstance(error,WatchError):raise
            raise WatchError('collector-output-unconfirmed') from None

    def lease(self,name):
        file=self.store.root/(name+'.lock')
        if file.is_symlink():raise WatchError('watch-lock-unsafe')
        stream=file.open('a');os.fchmod(stream.fileno(),0o600)
        try:fcntl.flock(stream,fcntl.LOCK_EX|fcntl.LOCK_NB)
        except BlockingIOError:stream.close();raise WatchError('watch-busy') from None
        return stream

    def sync(self,project='all',background=True):
        if not self.store or self.error:raise WatchError('watch-store-unavailable')
        if project!='all' and project not in PROJECTS:raise WatchError('unknown-project')
        lease=self.lease('collect')
        try:selected=[self.store.settings(p) for p in (PROJECTS if project=='all' else [project])]
        except Exception:lease.close();raise
        selected=[s for s in selected if s['enabled'] and s['retry_at']<=time.time()]
        if not selected:lease.close();raise WatchError('watch-disabled-or-cooling-down')
        self.running=True
        def work():
            try:
                for settings in selected:
                    if self.stop_event.is_set():break
                    self.store.begin(settings['project'])
                    try:
                        snapshot=self.collect(settings);self.store.finish(settings,snapshot=snapshot)
                    except WatchError as error:self.store.finish(settings,error=str(error),retry_at=error.retry_at or time.time()+60)
                    except Exception:self.store.finish(settings,error='collection-unconfirmed',retry_at=time.time()+60)
            finally:self.running=False;lease.close()
        if background:
            try:self.worker=threading.Thread(target=work,daemon=True);self.worker.start()
            except Exception:self.running=False;lease.close();raise
        else:work()
        return [s['project'] for s in selected]

    def listing(self,before=None):
        if not self.store or self.error:raise WatchError('watch-store-unavailable')
        data=self.store.listing(before);data.update(auto_enabled=self.enabled,interval_seconds=self.interval,running=self.running,
            poller_running=bool(self.leader),error=self.error,mode='polling and isolated signed webhook inbox')
        return data

    def start(self):
        if not self.enabled or not self.store:return
        try:self.leader=self.lease('poller')
        except WatchError:return
        def loop():
            # Opt-in never immediately launches network work or backfills missed ticks.
            while not self.stop_event.wait(self.interval):
                try:self.sync()
                except (WatchError,OSError,sqlite3.DatabaseError):continue
            self.leader.close();self.leader=None
        threading.Thread(target=loop,daemon=True).start()

    def close(self):
        self.stop_event.set()


